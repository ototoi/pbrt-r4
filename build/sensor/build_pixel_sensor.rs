// Orchestrator: compute the precomputed PixelSensor tables that
// runtime r4 looks up. Mirrors pbrt-v4 `PixelSensor` construction
// (film.h:45-78) for the named-sensor + whitebalance=6500 +
// outputColorSpace=sRGB-D65 case (the default v4 picks when a scene
// specifies a named sensor).
//
// Output: $OUT_DIR/pixel_sensor_data.rs with one
// `SensorEntry { name, r_dense, g_dense, b_dense, xyz_from_sensor_rgb }`
// per sensor in `build/sensor/sensor_data.rs::SENSORS`.

use crate::spectrum::cie_data::{CIE_X, CIE_Y, CIE_Z};
use crate::spectrum::config::Float;
use std::env;
use std::fs;
use std::path::Path;

use super::illuminant;
use super::math;
use super::sensor_data;
use super::swatch_data;

fn format_dense_array(name: &str, values: &[Float]) -> String {
    let mut s = String::new();
    s.push_str("#[rustfmt::skip]\n");
    s.push_str(&format!("static {}: [Float; DENSE_N] = [\n", name));
    for chunk in values.chunks(8) {
        s.push_str("    ");
        for v in chunk {
            s.push_str(&format!("{:.10}, ", v));
        }
        s.push('\n');
    }
    s.push_str("];\n");
    s
}

fn format_mat3(name: &str, m: &[[Float; 3]; 3]) -> String {
    let mut s = String::new();
    s.push_str(&format!("static {}: [[Float; 3]; 3] = [\n", name));
    for row in m {
        s.push_str(&format!(
            "    [{:.12e}, {:.12e}, {:.12e}],\n",
            row[0], row[1], row[2]
        ));
    }
    s.push_str("];\n");
    s
}

pub fn build_core(path: &str) {
    // D65 sensor illuminant (whiteBalanceTemp=6500) and CIE XYZ at 1nm.
    let d65 = illuminant::d_illuminant_dense(6500.0);
    let xbar = CIE_X.to_vec();
    let ybar = CIE_Y.to_vec();
    let zbar = CIE_Z.to_vec();

    let sensor_white_y = math::inner_product(&d65, &ybar);

    // Densify the 24 swatch reflectances once -- they're sensor-independent.
    let swatches: Vec<Vec<Float>> = (0..swatch_data::N_SWATCHES)
        .map(|i| math::densify(&swatch_data::SWATCH_LAMBDA, &swatch_data::SWATCH_VALUES[i]))
        .collect();

    let mut out = String::new();
    out.push_str("// Auto-generated by build/sensor/build_pixel_sensor.rs; do not edit.\n");
    out.push_str("use crate::util::base::Float;\n\n");
    out.push_str(&format!(
        "pub const DENSE_LAMBDA_MIN: u32 = {};\n",
        crate::spectrum::config::LAMBDA_MIN
    ));
    out.push_str(&format!(
        "pub const DENSE_LAMBDA_MAX: u32 = {};\n",
        crate::spectrum::config::LAMBDA_MAX
    ));
    out.push_str(
        "pub const DENSE_N: usize = (DENSE_LAMBDA_MAX - DENSE_LAMBDA_MIN + 1) as usize;\n\n",
    );
    out.push_str("pub struct SensorEntry {\n");
    out.push_str("    pub name: &'static str,\n");
    out.push_str("    pub r: &'static [Float; DENSE_N],\n");
    out.push_str("    pub g: &'static [Float; DENSE_N],\n");
    out.push_str("    pub b: &'static [Float; DENSE_N],\n");
    out.push_str("    pub xyz_from_sensor_rgb: &'static [[Float; 3]; 3],\n");
    out.push_str("}\n\n");

    let mut registry_lines: Vec<String> = Vec::new();
    for (name, r_vals, g_vals, b_vals) in sensor_data::SENSORS {
        // Densify this sensor's r/g/b channels to 1nm.
        let r_dense = math::densify(&sensor_data::SENSOR_LAMBDA, r_vals);
        let g_dense = math::densify(&sensor_data::SENSOR_LAMBDA, g_vals);
        let b_dense = math::densify(&sensor_data::SENSOR_LAMBDA, b_vals);

        // pbrt-v4 film.h:60 -- per-sensor white-G integral and the
        // (sensorWhiteY / sensorWhiteG) scaling applied to xyzOutput.
        let sensor_white_g = math::inner_product(&d65, &g_dense);
        let xyz_scale = sensor_white_y / sensor_white_g;

        // Project each swatch into rgbCamera (using sensor curves) and
        // xyzOutput (using CIE XYZ + chromatic-adaptation scaling).
        let mut rgb_camera: Vec<[Float; 3]> = Vec::with_capacity(swatch_data::N_SWATCHES);
        let mut xyz_output: Vec<[Float; 3]> = Vec::with_capacity(swatch_data::N_SWATCHES);
        for refl in &swatches {
            let rgb = math::project_reflectance(refl, &d65, &r_dense, &g_dense, &b_dense);
            let xyz = math::project_reflectance(refl, &d65, &xbar, &ybar, &zbar);
            rgb_camera.push(rgb);
            xyz_output.push([xyz[0] * xyz_scale, xyz[1] * xyz_scale, xyz[2] * xyz_scale]);
        }

        // Solve M such that M * rgbCamera[i] ≈ xyzOutput[i].
        let m = math::linear_least_squares_3x3(&rgb_camera, &xyz_output)
            .unwrap_or_else(|| panic!("LinearLeastSquares for {} failed", name));

        // Emit dense arrays + matrix + registry entry.
        let upper = name.to_uppercase();
        out.push_str(&format_dense_array(&format!("{}_R", upper), &r_dense));
        out.push('\n');
        out.push_str(&format_dense_array(&format!("{}_G", upper), &g_dense));
        out.push('\n');
        out.push_str(&format_dense_array(&format!("{}_B", upper), &b_dense));
        out.push('\n');
        out.push_str(&format_mat3(&format!("{}_XYZ_FROM_SENSOR_RGB", upper), &m));
        out.push('\n');

        registry_lines.push(format!(
            "    SensorEntry {{ name: \"{name}\", r: &{up}_R, g: &{up}_G, b: &{up}_B, xyz_from_sensor_rgb: &{up}_XYZ_FROM_SENSOR_RGB }},",
            name = name,
            up = upper
        ));
    }

    out.push_str("pub static SENSORS: &[SensorEntry] = &[\n");
    for line in &registry_lines {
        out.push_str(line);
        out.push('\n');
    }
    out.push_str("];\n");

    fs::write(path, &out).unwrap();
}

pub fn build() {
    for path in [
        "build/sensor/sensor_data.rs",
        "build/sensor/swatch_data.rs",
        "build/sensor/cie_s_data.rs",
        "build/sensor/illuminant.rs",
        "build/sensor/math.rs",
        "build/sensor/build_pixel_sensor.rs",
        "build/spectrum/cie_data.rs",
        "build/spectrum/spectrum_config.rs",
    ] {
        println!("cargo:rerun-if-changed={path}");
    }
    let target = "pixel_sensor_data.rs";
    let out_dir = env::var("OUT_DIR").unwrap();
    let path = Path::new(&out_dir).join(target);
    build_core(path.to_str().unwrap());
}
